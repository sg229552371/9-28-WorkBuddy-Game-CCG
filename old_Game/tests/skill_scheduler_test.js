/* 无头测试：SkillScheduler（每技能独立冷却 / 索敌 / 快照 / 策略表）
 * 运行：node skill_scheduler_test.js
 * 加载：vm 沙箱按 index.html 顺序加载 config.js → skill-scheduler.js（无真实 DOM）。 */
"use strict";

const fs = require("fs"), vm = require("vm");
const ctx = vm.createContext({ console: console });
for (const f of ["js/config.js", "js/skill-scheduler.js"]) {
  vm.runInContext(fs.readFileSync(f, "utf8"), ctx, { filename: f });
}

const driver = [
'/* ---- 测试夹具：装配 CFG.skillSystem ---- */',
'CFG.skillSystem.enabled = true;',
'CFG.skillSystem.migratedHeroIds = ["H1"];',
'CFG.skillSystem.castPolicies = {',
'  CP_NORMAL: { cdMulFloor: 0.5 },',
'  CP_ORBIT: { allowNoTarget: true, duration: 2.0, durationCap: 3.0 }',
'};',
'CFG.skillSystem.targetPolicies = { TP_NEAR: { range: 300 } };',
'CFG.skillSystem.skillDefs = {',
'  SK_A: { id:"SK_A", levels:[{cd:2},{cd:2}], castPolicyId:"CP_NORMAL", targetPolicyId:"TP_NEAR" },',
'  SK_B: { id:"SK_B", levels:[{cd:3}], castPolicyId:"CP_NORMAL", targetPolicyId:"TP_NEAR" },',
'  SK_C: { id:"SK_C", levels:[{cd:1}], castPolicyId:"CP_ORBIT", targetPolicyId:"TP_NEAR" }',
'};',
'',
'let passCount = 0, failCount = 0;',
'function check(name, cond) {',
'  if (cond) { passCount++; console.log("PASS " + name); }',
'  else { failCount++; console.log("FAIL " + name); }',
'}',
'function mkHero(o) {',
'  o = o || {};',
'  return {',
'    id: o.id || "H1", x: (o.x != null ? o.x : 0), y: (o.y != null ? o.y : 0),',
'    alive: (o.alive != null ? o.alive : true),',
'    stats: o.stats || { atk: 10, cdMul: 1 },',
'    skillState: { heroId: o.id || "H1", slotCount: 4, skills: o.skills || {} }',
'  };',
'}',
'function mkMon(id, x, y, r) { return { id: id, x: x, y: y, r: r || 8, dead: false }; }',
'function mkW(list) { return { monsters: list || [] }; }',
'',
'/* ---- 1. 每技能独立冷却（两技能互不阻塞） ---- */',
'{',
'  const h = mkHero({ skills: {',
'    SK_A: { id:"SK_A", level:1, cd:2, cdLeft:5 },',
'    SK_B: { id:"SK_B", level:1, cd:3, cdLeft:0 }',
'  } });',
'  const r = SkillScheduler.tick(mkW([mkMon(1, 50, 0)]), h, 0.1);',
'  check("每技能独立冷却：A 未就绪只有 B 施放", r.requests.length === 1 && r.requests[0].skillId === "SK_B");',
'  check("独立冷却：A 冷却不阻塞 B（两者都进入冷却）", h.skillState.skills.SK_A.cdLeft > 0 && h.skillState.skills.SK_B.cdLeft > 0);',
'}',
'',
'/* ---- 2. 无目标不消耗普通技能冷却 ---- */',
'{',
'  const h = mkHero({ skills: { SK_A: { id:"SK_A", level:1, cd:2, cdLeft:0 } } });',
'  const r = SkillScheduler.tick(mkW([]), h, 0.1);',
'  check("无目标不施放且不消耗普通冷却", r.requests.length === 0 && h.skillState.skills.SK_A.cdLeft === 0);',
'}',
'',
'/* ---- 3. 环绕类允许无目标 ---- */',
'{',
'  const h = mkHero({ skills: { SK_C: { id:"SK_C", level:1, cd:1, cdLeft:0 } } });',
'  const r = SkillScheduler.tick(mkW([]), h, 0.1);',
'  check("环绕允许无目标施放", r.requests.length === 1 && r.requests[0].skillId === "SK_C" && r.requests[0].target === null);',
'}',
'',
'/* ---- 4. 同距按稳定目标 ID 选目标 ---- */',
'{',
'  const h = mkHero({ skills: { SK_A: { id:"SK_A", level:1, cd:2, cdLeft:0 } } });',
'  const r = SkillScheduler.tick(mkW([mkMon(10, 100, 0), mkMon(5, -100, 0)]), h, 0.1);',
'  check("同距按稳定目标 ID 取小者", r.requests.length === 1 && r.requests[0].target.id === 5);',
'}',
'',
'/* ---- 5. 两技能同时就绪按稳定技能 ID 顺序 ---- */',
'{',
'  const h = mkHero({ skills: {',
'    SK_B: { id:"SK_B", level:1, cd:3, cdLeft:0 },',
'    SK_A: { id:"SK_A", level:1, cd:2, cdLeft:0 }',
'  } });',
'  const r = SkillScheduler.tick(mkW([mkMon(1, 50, 0)]), h, 0.1);',
'  check("两技能同就绪按稳定技能 ID 顺序", r.requests.length === 2 && r.requests[0].skillId === "SK_A" && r.requests[1].skillId === "SK_B");',
'}',
'',
'/* ---- 6. 快照只读且冻结 ---- */',
'{',
'  const build = { skillId:"SK_A", level:2, crystals:[{ crystalId:"CR_X", level:1 }], derivedCfg:{ k:1 }, graph:{ nodes:[] } };',
'  const snap = SkillScheduler.createCastSnapshot({ id:"H1" }, build, { atk:10, cdMul:1 }, 77);',
'  check("快照本体冻结", Object.isFrozen(snap));',
'  check("快照 stats 冻结且值正确", Object.isFrozen(snap.stats) && snap.stats.atk === 10);',
'  snap.stats.atk = 999;',
'  check("快照只读（写入无效）", snap.stats.atk === 10);',
'  check("快照字段齐全（castId/ownerId/skillId/level/crystals）",',
'    snap.castId === 77 && snap.ownerId === "H1" && snap.skillId === "SK_A" && snap.level === 2 &&',
'    snap.crystals.length === 1 && Object.isFrozen(snap.crystals) && Object.isFrozen(snap.derivedCfg));',
'  check("createSnapshot 与 createCastSnapshot 等价", SkillScheduler.createSnapshot({ id:"H1" }, build, { atk:1 }, 1).castId === 1);',
'}',
'',
'/* ---- 7. 冷却 / 范围 / 持续来自策略表（改表即生效） ---- */',
'{',
'  const cdClamped = SkillScheduler.cooldownFor(CFG.skillSystem.skillDefs.SK_A, 1, { cdMul: 0.1 }, { cdMulFloor: 0.5 });',
'  check("冷却缩减下限来自策略表（0.1 → 钳到 0.5）", Math.abs(cdClamped - 2 * 0.5) < 1e-9);',
'',
'  CFG.skillSystem.targetPolicies.TP_NEAR.range = 50;',
'  const h1 = mkHero({ skills: { SK_A: { id:"SK_A", level:1, cd:2, cdLeft:0 } } });',
'  const r1 = SkillScheduler.tick(mkW([mkMon(1, 100, 0)]), h1, 0.1);',
'  check("索敌范围来自策略表（改小 → 目标不可及）", r1.requests.length === 0);',
'',
'  CFG.skillSystem.targetPolicies.TP_NEAR.range = 300;',
'  const h2 = mkHero({ skills: { SK_A: { id:"SK_A", level:1, cd:2, cdLeft:0 } } });',
'  const r2 = SkillScheduler.tick(mkW([mkMon(1, 100, 0)]), h2, 0.1);',
'  check("索敌范围改回 → 目标可及", r2.requests.length === 1);',
'',
'  const iv = SkillScheduler.intervalFor(CFG.skillSystem.skillDefs.SK_C, 1, { cdMul: 1 }, { allowNoTarget:true, duration:5, durationCap:3 });',
'  check("环绕间隔 = max(冷却, 持续上限)", Math.abs(iv - 3) < 1e-9);',
'',
'  const iv2 = SkillScheduler.intervalFor(CFG.skillSystem.skillDefs.SK_C, 1, { cdMul: 1 }, { allowNoTarget:true, duration:2, durationCap:3 });',
'  check("环绕间隔 = max(冷却, 持续)（2 > 冷却 1）", Math.abs(iv2 - 2) < 1e-9);',
'}',
'',
'/* ---- 8. 死亡 / 失活停止施放 ---- */',
'{',
'  const h = mkHero({ alive:false, skills: { SK_A: { id:"SK_A", level:1, cd:2, cdLeft:0 } } });',
'  const r = SkillScheduler.tick(mkW([mkMon(1, 50, 0)]), h, 0.1);',
'  check("死亡停止施放并按原因回收", r.requests.length === 0 && r.stopped === true && r.reason === "DEAD");',
'}',
'',
'console.log("PASS 合计 = " + passCount + "   失败数 = " + failCount);',
'if (failCount > 0) throw new Error("skill_scheduler_test 存在失败用例");',
].join("\n");

vm.runInContext(driver, ctx, { filename: "driver" });
